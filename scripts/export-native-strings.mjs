// Writes the native app's strings (res/values/strings.xml, values-pt/strings.xml) from the Expo app's i18next locales
// (src/i18n/locales/en.json, pt.json). Keys are flattened with "_" (chatScreen.roleYou -> chatScreen_roleYou, "-" as "__");
// "{{var}}" placeholders and the _one/_other plural keys are kept as written, filled at runtime by ui/I18n.kt, so the
// texts stay exactly the TS app's.
//   node scripts/export-native-strings.mjs          # write
//   node scripts/export-native-strings.mjs --check  # exit 1 if out of date
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const res = join(root, "android-native/app/src/main/res");
const flatten = (o, p = "", out = {}) => {
  for (const [k, v] of Object.entries(o)) {
    // "-" isn't allowed in a resource name: "__" (already-shared -> already__shared), never in a TS key.
    const key = (p ? `${p}_${k}` : k).replace(/-/g, "__");
    if (v && typeof v === "object") flatten(v, key, out);
    else if (key in out) throw new Error(`two keys map to the resource name ${key}`);
    else out[key] = String(v);
  }
  return out;
};
// Android resource text: escape XML, apostrophes, quotes and a leading @ or ? (formatted="false": % stays as it is).
const escape = (s) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/"/g, '\\"')
    .replace(/\n/g, "\\n").replace(/^([@?])/, "\\$1");
const valid = (k) => /^[A-Za-z_][A-Za-z0-9_]*$/.test(k);

const en = flatten(JSON.parse(readFileSync(join(root, "src/i18n/locales/en.json"), "utf8")));
const pt = flatten(JSON.parse(readFileSync(join(root, "src/i18n/locales/pt.json"), "utf8")));
const bad = Object.keys(en).filter((k) => !valid(k));
if (bad.length) throw new Error(`keys that aren't valid resource names: ${bad.join(", ")}`);
const xml = (strings, note) =>
  `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/export-native-strings.mjs from ${note}. Do not edit by hand. -->\n<resources>\n` +
  Object.entries(strings).map(([k, v]) => `    <string name="${k}" formatted="false">${escape(v)}</string>`).join("\n") +
  `\n</resources>\n`;
// Portuguese falls back to English for a missing key (i18next's fallbackLng), so values-pt holds only translated keys.
const files = {
  [join(res, "values/strings.xml")]: xml({ app_name: "BoarLite", ...en }, "src/i18n/locales/en.json"),
  [join(res, "values-pt/strings.xml")]: xml(Object.fromEntries(Object.entries(pt).filter(([k]) => k in en)), "src/i18n/locales/pt.json"),
};
const check = process.argv.includes("--check");
let stale = 0;
for (const [path, text] of Object.entries(files)) {
  if (check) { if (!existsSync(path) || readFileSync(path, "utf8") !== text) { console.error(`out of date: ${path}`); stale++; } continue; }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
}
const missing = Object.keys(en).filter((k) => !(k in pt));
console.log(`${Object.keys(en).length} strings (en), ${Object.keys(pt).length} (pt); missing in pt: ${missing.length}`);
process.exit(stale ? 1 : 0);
